import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { createTheme } = await import(
  pathToFileURL(join(root, 'dist', 'esm', 'index.js')).href
);

const COLORS = {
  primary: '#940BDF',
  blue: '#3b82f6',
  amber: '#facc15',
  slate: '#0f172a',
};
const STEPS = [
  '50',
  '100',
  '200',
  '300',
  '400',
  '500',
  '600',
  '700',
  '800',
  '900',
  '950',
];

const SANS = 'ui-sans-serif, system-ui, sans-serif';
const MONO = 'ui-monospace, monospace';

const PAGE = { width: 960, margin: 16, gap: 16, pad: 28 };
const SWATCH = { width: 66, height: 64, gap: 4, pitch: 80 };
const PANEL_HEAD = 56;
const PANEL_FOOT = 20;

const MODES = [
  {
    key: 'light',
    title: 'Light mode',
    bg: '#ffffff',
    border: '#e2e8f0',
    text: '#0f172a',
    muted: '#64748b',
    stroke: 'rgba(15, 23, 42, 0.12)',
  },
  {
    key: 'dark',
    title: 'Dark mode',
    bg: '#0b1020',
    border: '#1e293b',
    text: '#f1f5f9',
    muted: '#94a3b8',
    stroke: 'rgba(255, 255, 255, 0.16)',
  },
];

const channel = (value) => {
  const v = value / 255;
  return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};

const luminance = (hex) => {
  const n = Number.parseInt(hex.slice(1), 16);
  return (
    0.2126 * channel((n >> 16) & 255) +
    0.7152 * channel((n >> 8) & 255) +
    0.0722 * channel(n & 255)
  );
};

const ratio = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const readableOn = (hex) =>
  ratio(hex, '#ffffff') >= ratio(hex, '#000000') ? '#ffffff' : '#000000';

const theme = createTheme(COLORS);

const names = Object.keys(COLORS);
const rowsWidth = STEPS.length * SWATCH.width + (STEPS.length - 1) * SWATCH.gap;
const panelWidth = PAGE.width - PAGE.margin * 2;
const rowsX = PAGE.margin + panelWidth - PAGE.pad - rowsWidth;
const panelHeight = PANEL_HEAD + names.length * SWATCH.pitch + PANEL_FOOT;
const pageHeight =
  PAGE.margin * 2 + MODES.length * panelHeight + (MODES.length - 1) * PAGE.gap;

const swatch = (mode, name, step, index, y) => {
  const { hex } = theme.scales[name][mode.key].steps[step];
  const x = rowsX + index * (SWATCH.width + SWATCH.gap);
  const ink = readableOn(hex);
  return [
    `<rect x="${x}" y="${y}" width="${SWATCH.width}" height="${SWATCH.height}" rx="6" fill="${hex}" stroke="${mode.stroke}"/>`,
    `<text x="${x + 8}" y="${y + 24}" font-family="${SANS}" font-size="13" font-weight="700" fill="${ink}">${step}</text>`,
    `<text x="${x + 8}" y="${y + 48}" font-family="${MONO}" font-size="10.5" fill="${ink}">${hex}</text>`,
  ].join('\n');
};

const row = (mode, name, y) =>
  [
    `<text x="${PAGE.margin + PAGE.pad}" y="${y + 26}" font-family="${SANS}" font-size="15" font-weight="600" fill="${mode.text}">${name}</text>`,
    `<text x="${PAGE.margin + PAGE.pad}" y="${y + 46}" font-family="${MONO}" font-size="11" fill="${mode.muted}">${COLORS[name]}</text>`,
    ...STEPS.map((step, index) => swatch(mode, name, step, index, y)),
  ].join('\n');

const panel = (mode, index) => {
  const top = PAGE.margin + index * (panelHeight + PAGE.gap);
  const rows = names.map((name, i) =>
    row(mode, name, top + PANEL_HEAD + i * SWATCH.pitch),
  );
  return [
    `<rect x="${PAGE.margin}" y="${top}" width="${panelWidth}" height="${panelHeight}" rx="14" fill="${mode.bg}" stroke="${mode.border}"/>`,
    `<text x="${PAGE.margin + PAGE.pad}" y="${top + 34}" font-family="${SANS}" font-size="17" font-weight="700" fill="${mode.text}">${mode.title}</text>`,
    ...rows,
  ].join('\n');
};

const scales = [
  `<svg xmlns="http://www.w3.org/2000/svg" width="${PAGE.width}" height="${pageHeight}" viewBox="0 0 ${PAGE.width} ${pageHeight}" role="img" aria-label="Shade scales generated by createTheme for four colors, in light and dark mode">`,
  `<rect width="${PAGE.width}" height="${pageHeight}" fill="#f1f5f9"/>`,
  ...MODES.map(panel),
  '</svg>',
  '',
].join('\n');

const outDir = join(root, 'assets');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'scales.svg'), scales);
